# -*- coding: utf-8 -*-
"""3DGS 标准 .ply 读写（不依赖 plyfile，纯 numpy 解析二进制 PLY）。

格式与官方 graphdeco-inria/gaussian-splatting 导出的 point_cloud.ply 完全兼容，
因此成果模型可以直接拖进 SuperSplat / antimatter15-splat / nerfstudio 等查看器。
"""
from __future__ import annotations

import struct
from pathlib import Path
from typing import Dict, List, Tuple

import numpy as np

# ply 类型 -> numpy 类型
_PLY2NP = {
    "char": "i1", "int8": "i1", "uchar": "u1", "uint8": "u1",
    "short": "i2", "int16": "i2", "ushort": "u2", "uint16": "u2",
    "int": "i4", "int32": "i4", "uint": "u4", "uint32": "u4",
    "float": "f4", "float32": "f4", "double": "f8", "float64": "f8",
}


def _read_header(f) -> Tuple[str, List[Tuple[str, str]], int, int]:
    """返回 (format, [(name, type)], vertex_count, header_bytes)。"""
    fmt = "ascii"
    props: List[Tuple[str, str]] = []
    count = 0
    nbytes = 0
    while True:
        line = f.readline()
        if not line:
            raise ValueError("PLY 头不完整")
        nbytes += len(line)
        s = line.decode("ascii", "ignore").strip()
        if s.startswith("format"):
            fmt = s.split()[1]
        elif s.startswith("element vertex"):
            count = int(s.split()[-1])
        elif s.startswith("property") and count:
            parts = s.split()
            if parts[1] != "list":
                props.append((parts[2], parts[1]))
        elif s == "end_header":
            break
    return fmt, props, count, nbytes


def read_ply(path: str | Path) -> Dict[str, np.ndarray]:
    """读取 3DGS .ply，返回各属性的 numpy 数组字典。"""
    with open(path, "rb") as f:
        fmt, props, count, _ = _read_header(f)
        if fmt == "ascii":
            data = np.loadtxt(f, max_rows=count)
            if data.ndim == 1:
                data = data[None, :]
            return {name: data[:, i] for i, (name, _) in enumerate(props)}
        dtype = np.dtype([(name, "<" + _PLY2NP[typ]) for name, typ in props])
        buf = f.read(dtype.itemsize * count)
        arr = np.frombuffer(buf, dtype=dtype, count=count)
        return {name: np.asarray(arr[name]) for name, _ in props}


def write_ply(path: str | Path, data: Dict[str, np.ndarray],
              comments: List[str] | None = None) -> str:
    """写出 3DGS 标准 .ply（binary_little_endian）。"""
    path = str(path)
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    names = list(data.keys())
    count = len(data[names[0]])
    dtype = np.dtype([(n, "<f4") for n in names])
    arr = np.empty(count, dtype=dtype)
    for n in names:
        arr[n] = np.asarray(data[n], np.float32).reshape(count)

    header = ["ply", "format binary_little_endian 1.0"]
    for c in (comments or ["Generated by aerosky 3D Gaussian Splatting module"]):
        header.append("comment " + c)
    header.append(f"element vertex {count}")
    header += [f"property float {n}" for n in names]
    header.append("end_header")
    with open(path, "wb") as f:
        f.write(("\n".join(header) + "\n").encode("ascii"))
        f.write(arr.tobytes())
    return path


# ------------------------------------------------------------------ 语义封装
def gaussians_to_ply(path, means, scales, quats, opacities, shs, sh_degree: int) -> str:
    """把训练好的高斯参数写成 3DGS 官方格式。

    f_dc_* 保存 0 阶球谐系数；f_rest_* 保存高阶系数（按通道转置存放，与官方一致）。
    """
    means = np.asarray(means, np.float32)
    scales = np.asarray(scales, np.float32)
    quats = np.asarray(quats, np.float32)
    opac = np.asarray(opacities, np.float32).reshape(-1)
    shs = np.asarray(shs, np.float32)                      # (N, C, 3)
    N, C, _ = shs.shape
    out: Dict[str, np.ndarray] = {
        "x": means[:, 0], "y": means[:, 1], "z": means[:, 2],
        "nx": np.zeros(N, np.float32), "ny": np.zeros(N, np.float32), "nz": np.zeros(N, np.float32),
        "f_dc_0": shs[:, 0, 0], "f_dc_1": shs[:, 0, 1], "f_dc_2": shs[:, 0, 2],
    }
    if C > 1:
        rest = shs[:, 1:, :].transpose(0, 2, 1).reshape(N, -1)   # 通道优先，与官方一致
        for i in range(rest.shape[1]):
            out[f"f_rest_{i}"] = rest[:, i]
    out["opacity"] = opac
    out["scale_0"] = scales[:, 0]
    out["scale_1"] = scales[:, 1]
    out["scale_2"] = scales[:, 2]
    out["rot_0"] = quats[:, 0]
    out["rot_1"] = quats[:, 1]
    out["rot_2"] = quats[:, 2]
    out["rot_3"] = quats[:, 3]
    return write_ply(path, out, comments=[f"aerosky 3DGS sh_degree={sh_degree}"])


def ply_to_gaussians(path) -> Dict[str, np.ndarray]:
    """把 3DGS .ply 解析回参数字典（数值为"已激活"的物理量）。"""
    d = read_ply(path)
    N = len(d["x"])
    means = np.stack([d["x"], d["y"], d["z"]], axis=1).astype(np.float32)
    scales = np.stack([d["scale_0"], d["scale_1"], d["scale_2"]], axis=1).astype(np.float32)
    scales = np.exp(scales)                                     # 存储的是 log 尺度
    quats = np.stack([d["rot_0"], d["rot_1"], d["rot_2"], d["rot_3"]], axis=1).astype(np.float32)
    quats = quats / np.maximum(np.linalg.norm(quats, axis=1, keepdims=True), 1e-8)
    opac = _sigmoid(np.asarray(d["opacity"], np.float32))
    dc = np.stack([d["f_dc_0"], d["f_dc_1"], d["f_dc_2"]], axis=1).astype(np.float32)
    rest_names = sorted([k for k in d if k.startswith("f_rest_")],
                        key=lambda k: int(k.split("_")[-1]))
    if rest_names:
        rest = np.stack([d[k] for k in rest_names], axis=1).astype(np.float32)
        C = rest.shape[1] // 3 + 1
        rest = rest.reshape(N, 3, C - 1).transpose(0, 2, 1)
        shs = np.concatenate([dc[:, None, :], rest], axis=1)
    else:
        shs = dc[:, None, :]
    return {"means": means, "scales": scales, "quats": quats,
            "opacities": opac, "shs": shs}


def sh_degree_of(path) -> int:
    d = read_ply(path)
    n = sum(1 for k in d if k.startswith("f_rest_"))
    return int(round(np.sqrt(n // 3 + 1))) - 1


def _sigmoid(x):
    return 1.0 / (1.0 + np.exp(-np.clip(x, -60, 60)))
